#!/bin/bash

# --- Конфигурация ---
# Файл, появления которого мы ждем.
FILENAME="key.json"
# Директория, в которой мы ждем файл (~ это домашняя директория).
# Переменная $HOME надежнее, чем ~, внутри скриптов.
TARGET_DIR="/home/yc-user"
# Таймаут в секундах.
TIMEOUT=60
# Интервал проверки в секундах.
INTERVAL=2
# --- Конец конфигурации ---

# Собираем полный путь к файлу для проверок и сообщений
FULL_PATH="$TARGET_DIR/$FILENAME"

echo "Ожидание появления файла: $FULL_PATH"
echo "Таймаут: ${TIMEOUT} сек. Интервал проверки: ${INTERVAL} сек."

# Сбрасываем встроенный счетчик секунд в 0
SECONDS=0

# Запускаем цикл, который будет работать, пока файл НЕ существует.
# Конструкция `[ ! -e "путь" ]` проверяет отсутствие файла или директории.
# Это более надежный и эффективный способ, чем анализ вывода `ls`.
while [ ! -e "$FULL_PATH" ]; do
  # Проверяем, не превышен ли таймаут.
  if (( SECONDS >= TIMEOUT )); then
    echo -e "\nОшибка: Таймаут (${TIMEOUT} сек) истек. Файл '$FILENAME' так и не появился."
    exit 1
  fi

  # Выводим точку, чтобы визуально показать, что скрипт работает и ждет.
  echo -n "."

  # Ждем указанный интервал перед следующей проверкой.
  sleep "$INTERVAL"
done

# Если мы вышли из цикла, значит файл появился.
# Переменная SECONDS будет содержать точное время ожидания.
WAIT_TIME=$SECONDS

echo -e "\nГотово! Файл '$FILENAME' найден."
echo "Время ожидания составило: ${WAIT_TIME} секунд."

exit 0